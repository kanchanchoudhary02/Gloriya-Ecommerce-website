export const UPLOAD_CATEGORY_BY_FILE = new Map(
  UPLOAD_CATALOG.flatMap(group => group.files.map(file => [file, group]))
);

export const UPLOAD_GROUP_BY_FILE = UPLOAD_CATEGORY_BY_FILE;

export function uploadPath(file) {
  return U(file);
}

export function galleryFilesForGroup(group) {
  const seen = new Set();
  const out = [];
  for (const file of group.files) {
    const key = file
      .replace(/^\d+-/, "")
      .replace(/_(?:\d+)(?=\.[^.]+$)/, "")
      .replace(/\.[^.]+$/, "");
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(file);
    if (out.length >= 10) break;
  }
  return out;
}
